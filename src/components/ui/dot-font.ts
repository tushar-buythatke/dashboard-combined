// Returns a rows x cols bitmap for `text`, one blank column between glyphs.
export function dotBitmap(text: string): { cols: number; rows: number; on: (x: number, y: number) => boolean } {
  const chars = [...text.toUpperCase()].map((c) => G[c] ?? G[' ']);
  const cols = Math.max(1, chars.length * 6 - 1);
  return {
    cols,
    rows: 7,
    on: (x, y) => {
      const ci = Math.floor(x / 6);
      const cx = x % 6;
      if (cx === 5 || !chars[ci]) return false;
      return ((chars[ci][y] >> (4 - cx)) & 1) === 1;
    },
  };
}
